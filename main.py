# Generate Chart Function

def generate_chart(data, prompt):
    try:

        # Set your OpenAI API key
        prompt = f"""You are an AI Assistant. Here is some data:
                    {data}

                    Using this data, make a chart that pertains to the following user prompt. 
                    

                     If the following prompt is not relevant to the data, respond with a lowercase "no". 
                     Any prompt that is not specifically asking for a piece of data relevant to the chart should be responded to with a no. 
                     This includes casual conversation, asking about other data sets, etc. Otherwise, Return a string that can be directly parsed by JSON.parse() with no other information except the vega lite specs. Don't make the height or width greater than 400px. Only return one chart no matter what.

                     {prompt}
                     """,
        print(prompt)
        # Call the OpenAI API via LangChain
        chat_completion = client.chat.completions.create(
            messages=[
                {
                    "role": "user",
                    "content": f"{prompt}",
                }
            ],
            model="gpt-4o-mini",
        )
        print(chat_completion)
        print("Returning Generated Chart")
        return chat_completion.choices[0].message.content
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))
    
    
