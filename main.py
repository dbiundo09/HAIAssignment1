# ReAct Tool Calling Loop
def query(question : str, data : str, max_iterations = 10):
    print(data)
    print(question)
    system_prompt = "You are an AI Assistant. The user will give you some data and ask you a question. If the question is not relevant to the data, respond with only 'no'. It can either involve data analysis, chart generation, or both. You will return a dictionary of the form {chart : [VegaLite Chart as JSON], analysis : [Markdown as a string of any analysis or chart description that can be rendered with <ReactMarkdown remarkPlugins={[remarkGfm]}>{message}</ReactMarkdown>]}. The VegaLite chart will always be generated with the generate_chart tool, but the analysis Mardkwon can either be done by executing python code using the tool, or just a description of the chart of no analysis is required. This is very important: Remember that whenever you are using the execute pandas datafrom tool, the code must print out any results for it to be captured using the python print(...) function! No matter what, a dictionary of the form {chart : [VegaLite Chart as JSON or null], analysis : [Markdown of any analysis or chart description that can be rendered with <ReactMarkdown remarkPlugins={[remarkGfm]}>{message}</ReactMarkdown>]}, must be returned, and if you are just returning a markdown as a string include it in the analysis key. If the user doesn't explicitly ask for a graph, you can assume one will not be included. Remember, analysis must be a markdown string. It cannot be anything else, html, etc." 
    messages = [{"role": "system", "content": system_prompt}]
    messages.append({"role": "user", "content": "Here is the data:"  + data + "\n here is the question: " + question})
    i = 0
    while i < max_iterations:
        i += 1
        print("iteration:", i)
        response = client.chat.completions.create(
            model="gpt-4o-mini", temperature=0.0, messages=messages, tools=tools
        )

        if response.choices[0].message.content != None:
            print_red(response.choices[0].message.content)


        # if not function call
        if response.choices[0].message.tool_calls == None:
            break

        # if function call
        messages.append(response.choices[0].message)
        for tool_call in response.choices[0].message.tool_calls:
            print_blue("calling:", tool_call.function.name, "with", tool_call.function.arguments)
            # call the function
            arguments = json.loads(tool_call.function.arguments)
            function_to_call = tool_map[tool_call.function.name]
            result = function_to_call(**arguments)


            # create a message containing the result of the function call
            result_content = json.dumps({**arguments, "result": result})
            function_call_result_message = {
                "role": "tool",
                "content": result_content,
                "tool_call_id": tool_call.id,
            }
            print_blue("action result:", (result_content))

            messages.append(function_call_result_message)
        if i == max_iterations and response.choices[0].message.tool_calls != None:
            print_red("Max iterations reached")
            return "The tool agent could not complete the task in the given time. Please try again."
    return response.choices[0].message.content




